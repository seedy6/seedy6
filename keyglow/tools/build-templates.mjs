// Builds js/audio/piano-templates.js: what each of the 88 keys of a real grand piano looks like to
// the detector. Used until the person calibrates their own keyboard.
//
//   node tools/build-templates.mjs <dir of 48 kHz mono float32 files named C4.f32, Ds4.f32, …>
//
// The files are the Salamander Grand Piano samples (CC-BY 3.0, Alexander Holm), decoded with
//   ffmpeg -i C4v8.mp3 -t 3 -ac 1 -ar 48000 -f f32le C4.f32

import fs from 'node:fs';
import path from 'node:path';
import { SpectrumAnalyzer, NUM_BANDS, normalize, packTemplate } from '../app/src/main/assets/web/js/audio/dsp.js';
import { loadSampleSet, renderKey } from '../tests/helpers.mjs';

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-templates.mjs <pcm dir>'); process.exit(1); }
const SR = 48000;
const set = loadSampleSet(dir);
const an = new SpectrumAnalyzer(SR);
const out = {};
for (let m = 21; m <= 108; m++) {
  const pcm = renderKey(set, m, SR, 0.6);
  const sum = new Float64Array(NUM_BANDS);
  const hop = 480;
  for (let start = Math.round(0.05 * SR); start + an.n < pcm.length && start < 0.45 * SR; start += hop) {
    const { bands } = an.analyze(pcm, start);
    for (let b = 0; b < NUM_BANDS; b++) sum[b] += bands[b];
  }
  out[m] = packTemplate(normalize(sum));
}
const file = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../app/src/main/assets/web/js/audio/piano-templates.js');
fs.writeFileSync(file,
  '// Generated by tools/build-templates.mjs from the Salamander Grand Piano (CC-BY 3.0, Alexander Holm).\n' +
  '// Each key: 313 log-frequency bands, 8-bit log scale, base64.\n' +
  'export default ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, fs.statSync(file).size, 'bytes');
